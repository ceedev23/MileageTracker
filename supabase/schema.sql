-- 1. Trips Table
CREATE TABLE IF NOT EXISTS public.trips (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT UNIQUE,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    start_date BIGINT NOT NULL,
    end_date BIGINT NOT NULL,
    distance_km DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    type TEXT, -- 'Business', 'Personal', or NULL (Unclassified)
    start_address TEXT,
    end_address TEXT,
    purpose TEXT,
    vehicle TEXT,
    path_json TEXT DEFAULT '[]',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Gas Receipts Table
CREATE TABLE IF NOT EXISTS public.gas_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT UNIQUE,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    timestamp BIGINT NOT NULL,
    image_path TEXT,
    merchant TEXT,
    total_amount DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    currency TEXT DEFAULT '$',
    fuel_type TEXT,
    gallons_or_liters DOUBLE PRECISION,
    unit TEXT DEFAULT 'L',
    price_per_unit DOUBLE PRECISION,
    receipt_date TEXT,
    payment_method TEXT,
    raw_extraction TEXT,
    trip_id BIGINT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. User Settings Table
CREATE TABLE IF NOT EXISTS public.user_settings (
    user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    auto_detect BOOLEAN DEFAULT TRUE,
    dwell_minutes INTEGER DEFAULT 5,
    unit TEXT DEFAULT 'km',
    reimbursement_rate DOUBLE PRECISION DEFAULT 0.70,
    vehicle_name TEXT DEFAULT 'Primary Vehicle',
    annual_goal DOUBLE PRECISION DEFAULT 15000.0,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_trips_user_id ON public.trips(user_id);
CREATE INDEX IF NOT EXISTS idx_trips_client_id ON public.trips(client_id);
CREATE INDEX IF NOT EXISTS idx_trips_start_date ON public.trips(start_date DESC);

CREATE INDEX IF NOT EXISTS idx_gas_receipts_user_id ON public.gas_receipts(user_id);
CREATE INDEX IF NOT EXISTS idx_gas_receipts_client_id ON public.gas_receipts(client_id);
CREATE INDEX IF NOT EXISTS idx_gas_receipts_timestamp ON public.gas_receipts(timestamp DESC);

-- Fuel volume is litres in Canada. Safe to re-run on an existing project.
ALTER TABLE public.gas_receipts ALTER COLUMN unit SET DEFAULT 'L';

-- Enable Row Level Security (RLS)
ALTER TABLE public.trips ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.gas_receipts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_settings ENABLE ROW LEVEL SECURITY;

-- Trips Policies:
-- Allow authenticated users to view/modify their own trips
CREATE POLICY "Authenticated users can manage their trips"
    ON public.trips
    FOR ALL
    TO authenticated
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

-- Allow anonymous access for guest drivers or when user_id is null
CREATE POLICY "Anon users can access unassigned trips"
    ON public.trips
    FOR ALL
    TO anon
    USING (user_id IS NULL OR user_id = auth.uid())
    WITH CHECK (user_id IS NULL OR user_id = auth.uid());

-- Gas Receipts Policies:
CREATE POLICY "Authenticated users can manage their gas receipts"
    ON public.gas_receipts
    FOR ALL
    TO authenticated
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

-- Guest receipts stay on-device; do not grant anonymous receipt access.
-- For private photo storage, also apply receipt_photo_storage.sql.

-- User Settings Policies:
CREATE POLICY "Users can manage their own settings"
    ON public.user_settings
    FOR ALL
    TO authenticated
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

-- Enable Supabase Realtime for instant synchronization across devices
ALTER PUBLICATION supabase_realtime ADD TABLE public.trips;
ALTER PUBLICATION supabase_realtime ADD TABLE public.gas_receipts;
